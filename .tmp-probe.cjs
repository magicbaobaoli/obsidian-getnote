const { JSDOM } = require('jsdom')
const dom = new JSDOM('<div id="a"><p>第一段 桂圆 文字</p><p>第二段</p></div>', { pretendToBeVisual: true })
const w = dom.window, d = w.document
const p = d.querySelector('p')
const r = d.createRange()
r.setStart(p.firstChild, 0)
r.setEnd(p.firstChild, 5)
const sel = w.getSelection()
sel.removeAllRanges()
sel.addRange(r)
console.log('toString=', JSON.stringify(sel.toString()))
console.log('rect=', JSON.stringify(r.getBoundingClientRect()))
console.log('rangeCount=', sel.rangeCount, 'ancestor=', r.commonAncestorContainer.nodeName)